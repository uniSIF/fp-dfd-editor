/** Copilot Studio・エージェントビルダーの「指示」欄の上限 */
export const AGENT_INSTRUCTIONS_LIMIT = 8000;

/**
 * エージェントに与える指示。プロジェクト固有の補足情報（FR-IO-07）があれば末尾に足し、一般的な基準より優先させる。
 */
export function buildAgentInstructions(notes = '', agent: AgentKind = 'dfd'): string {
  const base = AGENTS[agent].instructions;
  const n = notes.trim();
  if (!n) return base;
  return `${base}
# プロジェクト固有の補足情報
以下はこのプロジェクトの業務・用語・見積もりの決まりです。要素の洗い出し、種別・複雑度の判定、名前の付け方では、上の一般的な基準よりこちらを優先してください。

${n}
`;
}

/** 書き出しダイアログの「依頼文と JSON をコピー」で使う依頼文 */
export function buildAgentRequest(json: string, request: string, withInstructions: boolean, notes = '', agent: AgentKind = 'dfd'): string {
  const ask = request.trim() || AGENTS[agent].defaultRequest;
  return [
    withInstructions ? `${buildAgentInstructions(notes, agent)}\n---\n` : '',
    `次の JSON は FP DFD Editor から書き出した DFD です。\n\n依頼: ${ask}\n\n\`\`\`json\n${json}\n\`\`\`\n`,
  ].join('');
}
